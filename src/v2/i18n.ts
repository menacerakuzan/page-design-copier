export type V2Key = keyof (typeof dict)["uk"];

export function useV2() {
  const { lang, setLang, tl } = useLang();
  const t = (key: V2Key) => dict[lang][key] as string;
  const list = (key: V2Key) => t(key).split("|");
  return { t, list, lang, setLang, tl };
}

/** Прибирає HTML-теги з опису з БД. */
export const plain = (html?: string | null) =>
  (html ?? "").replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();
